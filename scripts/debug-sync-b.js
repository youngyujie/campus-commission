const { chromium } = require('playwright-core')
const BASE = 'http://127.0.0.1:3100/'
;(async () => {
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const p = await ctx.newPage()
  p.on('pageerror', e => console.log('PAGEERROR', String(e)))
  p.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text()) })
  await p.goto(BASE, { waitUntil: 'networkidle' })
  await p.waitForTimeout(1800)
  await p.getByText('林小满', { exact: true }).first().click()
  await p.waitForTimeout(2500)
  const title = '调试B-' + Date.now()
  await p.goto(BASE + '#/pages/publish/publish')
  await p.waitForTimeout(1200)
  await p.locator('.input-title input').fill(title)
  await p.locator('.cat').nth(3).click()
  await p.locator('.textarea textarea').fill('这是一条用于验证双端共享数据的委托描述内容，请忽略')
  await p.locator('.money-input input').first().fill('12')
  await p.locator('.input input').first().fill('两江餐厅')
  await p.waitForTimeout(400)
  const cls = await p.locator('.submit-inline .btn').getAttribute('class')
  console.log('submit class:', cls)
  const formState = await p.evaluate(() => {
    const vals = [...document.querySelectorAll('input, textarea')].map(i => i.value).filter(Boolean)
    return vals
  })
  console.log('filled values:', JSON.stringify(formState))
  await p.locator('.submit-inline .btn').click()
  await p.waitForTimeout(500)
  console.log('after 0.5s body:', (await p.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(-300))
  await p.waitForTimeout(1500)
  console.log('after 2s body:', (await p.evaluate(() => document.body.innerText)).replace(/\n+/g, ' | ').slice(-300))
  await p.waitForTimeout(2000)
  await p.goto(BASE + '#/pages/hall/hall')
  await p.waitForTimeout(1500)
  const hall = await p.evaluate(() => document.body.innerText)
  console.log('hall has title:', hall.includes(title))
  await b.close()
})().catch(e => { console.error('ERR', e); process.exit(1) })
