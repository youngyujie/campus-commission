const { chromium } = require('playwright-core')
const BASE = 'http://127.0.0.1:3103/'
const readAvatar = (p) => p.evaluate(() => {
  const raw = JSON.parse(localStorage.getItem('campus_commission_state_v2'))
  const st = raw && raw.data ? raw.data : raw
  const me = st.users.find(u => u.id === st.sessionUserId)
  const dom = document.querySelector('.avatar-hit .av-emoji')
  return { store: me ? me.avatar : null, dom: dom ? dom.innerText : null }
})
;(async () => {
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const p = await ctx.newPage()
  await p.goto(BASE, { waitUntil: 'domcontentloaded' })
  await p.waitForSelector('.m-demo-item', { timeout: 30000 })
  await p.getByText('林小满', { exact: true }).first().click()
  await p.waitForTimeout(3000)
  await p.goto(BASE + '#/pages/mine/mine')
  await p.waitForTimeout(1500)
  console.log('before', await readAvatar(p))
  await p.locator('.avatar-hit').click()
  await p.waitForTimeout(500)
  await p.getByText('更改头像', { exact: true }).click()
  await p.waitForTimeout(500)
  await p.getByText('系统自带头像', { exact: true }).click()
  await p.waitForTimeout(600)
  console.log('opts', await p.locator('.avatar-opt').count())
  const target = p.locator('.avatar-opt').filter({ hasText: '🐻' })
  console.log('bear count', await target.count())
  if (await target.count()) await target.first().click()
  await p.waitForTimeout(800)
  console.log('after', await readAvatar(p))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
