const { chromium } = require('playwright-core')
const path = require('path')
const FILE = 'file://' + path.resolve(__dirname, '../校园委托-单文件版.html')
;(async () => {
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
  const p = await ctx.newPage()
  await p.goto(FILE, { waitUntil: 'networkidle' })
  await p.evaluate(() => localStorage.clear())
  await p.reload({ waitUntil: 'networkidle' })
  await p.waitForTimeout(1200)
  await p.getByText('许一帆', { exact: true }).first().click()
  await p.waitForTimeout(1400)
  await p.goto(FILE + '#/pages/verify/verify')
  await p.waitForTimeout(1000)
  await p.screenshot({ path: path.resolve(__dirname, '../preview/upgrade/11-verify-hint.png') })
  console.log('saved 11-verify-hint.png')
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
